//! The bash, zsh and fish completions, generated from the subcommand table. Package names come from
//! `paku __complete repo|installed` when the shell asks.
use crate::commands::{Complete, COMMANDS, MAINTAIN_FLAGS, SHELLS};

/// The script for a shell, or None for one paku doesn't know.
pub fn script(shell: &str) -> Option<String> {
    match shell {
        "bash" => Some(bash()),
        "zsh" => Some(zsh()),
        "fish" => Some(fish()),
        _ => None,
    }
}

/// The words (names and aliases) of the commands that complete `what`, joined by `sep`.
fn words_completing(what: Complete, sep: &str) -> String {
    COMMANDS.iter().filter(|c| c.complete == what).flat_map(|c| c.words()).collect::<Vec<_>>().join(sep)
}

fn all_words(sep: &str) -> String {
    COMMANDS.iter().flat_map(|c| c.words()).collect::<Vec<_>>().join(sep)
}

fn flags(sep: &str) -> String {
    MAINTAIN_FLAGS.iter().map(|(f, _)| *f).collect::<Vec<_>>().join(sep)
}

/// A single-quoted word for sh, bash, zsh and fish: the table's texts have no quote nor backslash (checked by a
/// test), so no escaping is needed (zsh's `\:` is literal inside single quotes there).
fn quoted(text: &str) -> String {
    debug_assert!(!text.contains('\''));
    format!("'{text}'")
}

fn bash() -> String {
    let mut s = String::from("# bash completion for paku (generated by `paku completions bash`)\n_paku() {\n");
    s.push_str("    local cur=${COMP_WORDS[COMP_CWORD]}\n");
    s.push_str("    if [[ $COMP_CWORD -eq 1 ]]; then\n");
    s.push_str(&format!("        mapfile -t COMPREPLY < <(compgen -W {} -- \"$cur\")\n", quoted(&all_words(" "))));
    s.push_str("        return\n    fi\n");
    s.push_str("    case ${COMP_WORDS[1]} in\n");
    // The package names come from the sync databases, which a third-party repo or mirror writes: they never go
    // through compgen -W, which expands its word list ($(...) included). paku filters them by the prefix
    let packages = |sources: &[&str]| {
        let lists = sources.iter().map(|w| format!("paku __complete {w} \"$cur\" 2>/dev/null")).collect::<Vec<_>>();
        format!("mapfile -t COMPREPLY < <({})", lists.join("; "))
    };
    for (what, action) in [
        (Complete::Repo, packages(&["repo"])),
        (Complete::Installed, packages(&["installed"])),
        (Complete::RepoAndInstalled, packages(&["repo", "installed"])),
        (
            Complete::Paths,
            "compopt -o filenames 2>/dev/null; mapfile -t COMPREPLY < <(compgen -f -- \"$cur\")".to_string(),
        ),
        (Complete::MaintainFlags, format!("mapfile -t COMPREPLY < <(compgen -W {} -- \"$cur\")", quoted(&flags(" ")))),
        (
            Complete::Shells,
            format!(
                "[[ $COMP_CWORD -eq 2 ]] && mapfile -t COMPREPLY < <(compgen -W {} -- \"$cur\")",
                quoted(&SHELLS.join(" "))
            ),
        ),
    ] {
        s.push_str(&format!("        {})\n            {action}\n            ;;\n", words_completing(what, "|")));
    }
    s.push_str("    esac\n}\ncomplete -F _paku paku\n");
    s
}

fn zsh() -> String {
    let mut s =
        String::from("#compdef paku\n# zsh completion for paku (generated by `paku completions zsh`)\n\n_paku() {\n");
    s.push_str("    local -a subcommands flags\n    subcommands=(\n");
    for c in COMMANDS {
        for w in c.words() {
            s.push_str(&format!("        {}\n", quoted(&format!("{w}:{}", c.description.replace(':', "\\:")))));
        }
    }
    s.push_str("    )\n    flags=(\n");
    for (flag, description) in MAINTAIN_FLAGS {
        s.push_str(&format!("        {}\n", quoted(&format!("{flag}:{}", description.replace(':', "\\:")))));
    }
    s.push_str("    )\n");
    s.push_str("    if (( CURRENT == 2 )); then\n        _describe -t commands 'paku command' subcommands\n        return\n    fi\n");
    s.push_str("    case $words[2] in\n");
    let packages = |sources: &[&str]| {
        let lists =
            sources.iter().map(|w| format!("${{(f)\"$(paku __complete {w} 2>/dev/null)\"}}")).collect::<Vec<_>>();
        format!("compadd -- {}", lists.join(" "))
    };
    for (what, action) in [
        (Complete::Repo, packages(&["repo"])),
        (Complete::Installed, packages(&["installed"])),
        (Complete::RepoAndInstalled, packages(&["repo", "installed"])),
        (Complete::Paths, "_files".to_string()),
        (Complete::MaintainFlags, "_describe -t flags 'cachy-update flag' flags".to_string()),
        (Complete::Shells, format!("(( CURRENT == 3 )) && compadd -- {}", SHELLS.join(" "))),
    ] {
        s.push_str(&format!("        {})\n            {action}\n            ;;\n", words_completing(what, "|")));
    }
    s.push_str("    esac\n}\n\n");
    // Autoloaded from site-functions, the file is the function; sourced, it registers it
    s.push_str("if [[ $funcstack[1] == _paku ]]; then\n    _paku \"$@\"\nelse\n    compdef _paku paku\nfi\n");
    s
}

fn fish() -> String {
    let mut s = String::from("# fish completions for paku (generated by `paku completions fish`)\n\n");
    s.push_str("# No files unless the subcommand takes paths\ncomplete -c paku -f\n\n");
    for c in COMMANDS {
        let words = c.words().collect::<Vec<_>>().join(" ");
        s.push_str(&format!(
            "complete -c paku -n __fish_use_subcommand -a {} -d {}\n",
            quoted(&words),
            quoted(c.description)
        ));
    }
    s.push('\n');
    let seen = |what: Complete| quoted(&format!("__fish_seen_subcommand_from {}", words_completing(what, " ")));
    s.push_str(&format!("complete -c paku -n {} -a '(paku __complete repo)'\n", seen(Complete::Repo)));
    s.push_str(&format!("complete -c paku -n {} -a '(paku __complete installed)'\n", seen(Complete::Installed)));
    s.push_str(&format!(
        "complete -c paku -n {} -a '(paku __complete repo; paku __complete installed)'\n",
        seen(Complete::RepoAndInstalled)
    ));
    s.push_str(&format!("complete -c paku -n {} -F\n", seen(Complete::Paths)));
    for (flag, description) in MAINTAIN_FLAGS {
        s.push_str(&format!(
            "complete -c paku -n {} -l {} -d {}\n",
            seen(Complete::MaintainFlags),
            flag.trim_start_matches('-'),
            quoted(description)
        ));
    }
    s.push_str(&format!(
        "complete -c paku -n {} -a {}\n",
        quoted(&format!(
            "__fish_seen_subcommand_from {}; and not __fish_seen_subcommand_from {}",
            words_completing(Complete::Shells, " "),
            SHELLS.join(" ")
        )),
        quoted(&SHELLS.join(" "))
    ));
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;

    #[test]
    fn the_texts_need_no_escaping() {
        for c in COMMANDS {
            for text in c.words().chain([c.description]) {
                assert!(!text.contains('\'') && !text.contains('\\'), "{text}");
            }
        }
        for (flag, description) in MAINTAIN_FLAGS {
            assert!(!flag.contains('\'') && !description.contains('\''));
        }
    }

    #[test]
    fn bash_never_expands_the_package_names() {
        let text = bash();
        assert!(!text.contains("compgen -W \"$("), "{text}");
        assert!(text.contains("mapfile -t COMPREPLY < <(paku __complete repo \"$cur\" 2>/dev/null)"));
    }

    /// The bash completion with a package name that would run a command if anything expanded it.
    #[test]
    fn a_hostile_package_name_stays_text_in_bash() {
        let dir = std::env::temp_dir().join(format!("paku-hostile-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let pwned = dir.join("pwned");
        // A paku that answers __complete with the hostile name
        let fake = dir.join("paku");
        std::fs::write(&fake, format!("#!/bin/sh\nprintf '%s\\n' htop '$(touch {})'\n", pwned.display())).unwrap();
        std::fs::set_permissions(&fake, std::os::unix::fs::PermissionsExt::from_mode(0o755)).unwrap();
        let script = dir.join("c.bash");
        std::fs::write(&script, bash()).unwrap();
        let test = format!(
            "PATH={}:$PATH; source {}; COMP_WORDS=(paku install ''); COMP_CWORD=2; _paku; printf '%s\\n' \"${{COMPREPLY[@]}}\"",
            dir.display(),
            script.display()
        );
        match Command::new("bash").arg("-c").arg(&test).output() {
            Ok(out) => {
                assert!(!pwned.exists(), "the name ran a command");
                let lines = String::from_utf8_lossy(&out.stdout);
                assert!(lines.lines().any(|l| l.starts_with("$(touch")), "{lines}");
            }
            Err(_) if std::env::var_os("PAKU_REQUIRE_SHELLS").is_none() => eprintln!("bash not installed, skipped"),
            Err(e) => panic!("bash: {e}"),
        }
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn every_word_is_completed() {
        for shell in SHELLS {
            let text = script(shell).unwrap();
            for c in COMMANDS {
                for w in c.words() {
                    assert!(text.contains(w), "{shell}: {w}");
                }
            }
        }
        assert_eq!(script("tcsh"), None);
    }

    /// The shell checks the syntax when it's installed (CI installs the three); skipped otherwise.
    #[test]
    fn the_scripts_parse() {
        for shell in SHELLS {
            let file = std::env::temp_dir().join(format!("paku-completion-{}.{shell}", std::process::id()));
            std::fs::write(&file, script(shell).unwrap()).unwrap();
            let status = Command::new(shell).arg("-n").arg(&file).status();
            let _ = std::fs::remove_file(&file);
            match status {
                Ok(status) => assert!(status.success(), "{shell} -n failed"),
                Err(_) if std::env::var_os("PAKU_REQUIRE_SHELLS").is_none() => {
                    eprintln!("{shell} not installed, skipped")
                }
                Err(e) => panic!("{shell}: {e}"),
            }
        }
    }
}
